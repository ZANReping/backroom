/** 选一组对话（两人团体合并池，通用池权重 1:1） */
export function pickChatExchange(fa: string | undefined, fb: string | undefined, rnd: () => number = Math.random): ChatExchange {
  const own = [...(CHAT_FACTION[fa ?? 'meg'] ?? []), ...(fb && fb !== fa ? CHAT_FACTION[fb] ?? [] : [])]
  const list = own.length && rnd() < .5 ? own : CHAT_GENERAL
  return list[Math.floor(rnd() * list.length)]
}
