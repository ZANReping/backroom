import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { unzipSync } from 'fflate';

const assets = ['marble_01', 'wood_floor', 'white_plaster_02', 'fabric_pattern_05'];
const maps = [
  ['Diffuse', 'Color'],
  ['nor_gl', 'NormalGL'],
  ['Rough', 'Roughness'],
];
const outDir = join(process.cwd(), 'public', 'textures', 'l5');
const sources = new Map();
const ambientAssets = {
  Marble022: '红色调白脉石柱',
  Marble005: '白色细脉大理石地面',
  Wallpaper001A: '浅金色细颗粒压纹墙纸',
};

async function getJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response.json();
}

async function asJpeg(data, format) {
  if (format === 'jpg') return data;
  const { createCanvas, loadImage } = await import('@napi-rs/canvas');
  const image = await loadImage(data);
  const canvas = createCanvas(image.width, image.height);
  canvas.getContext('2d').drawImage(image, 0, 0);
  return canvas.toBuffer('image/jpeg', 92);
}

await mkdir(outDir, { recursive: true });
for (const asset of assets) {
  const files = await getJson(`https://api.polyhaven.com/files/${asset}`);
  for (const [apiMap, outputMap] of maps) {
    // Poly Haven's patterned fabrics expose their base color as col_01.
    const variants = (files[apiMap] ?? files[asset === 'fabric_pattern_05' && apiMap === 'Diffuse' ? 'col_01' : apiMap])?.['1k'];
    const format = variants?.jpg ? 'jpg' : variants?.png ? 'png' : null;
    if (!format) throw new Error(`Missing 1k jpg/png ${apiMap} map for ${asset}`);
    const source = variants[format];
    const response = await fetch(source.url);
    if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${source.url}`);
    const data = Buffer.from(await response.arrayBuffer());
    if (data.length === 0) throw new Error(`Empty download: ${source.url}`);
    const jpeg = await asJpeg(data, format);
    const path = join(outDir, `${asset}_${outputMap}.jpg`);
    await writeFile(path, jpeg);
    sources.set(`${asset}_${outputMap}`, source.url);
    console.log(`${path} (${jpeg.length} bytes)`);
  }
}

const ambientJson = await getJson('https://ambientcg.com/api/v2/full_json?include=downloadData&id=Marble022,Marble005,Wallpaper001A');
for (const asset of Object.keys(ambientAssets)) {
  const record = ambientJson.foundAssets.find((item) => item.assetId.toLowerCase() === asset.toLowerCase());
  const downloads = record?.downloadFolders?.default?.downloadFiletypeCategories?.zip?.downloads ?? [];
  const download = downloads.find((item) => item.attribute === '1K-JPG');
  if (!download) throw new Error(`Missing AmbientCG 1K-JPG ZIP for ${asset}`);
  const response = await fetch(download.fullDownloadPath);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${download.fullDownloadPath}`);
  const zip = unzipSync(new Uint8Array(await response.arrayBuffer()));
  for (const map of ['Color', 'NormalGL', 'Roughness']) {
    const entry = Object.entries(zip).find(([name]) => new RegExp(`_${map}\\.jpg$`, 'i').test(name));
    if (!entry || entry[1].length === 0) throw new Error(`Missing ${map} in ${asset} ZIP`);
    const path = join(outDir, `${asset}_${map}.jpg`);
    await writeFile(path, entry[1]);
    sources.set(`${asset}_${map}`, download.fullDownloadPath);
    console.log(`${path} (${entry[1].length} bytes)`);
  }
}

